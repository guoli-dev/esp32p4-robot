#pragma once

/**
 * @file mpu6050.h
 * @brief MPU6050 6轴 IMU 驱动 (I2C)
 *
 * 支持:
 *   - 陀螺仪 3 轴角速度读取 (rad/s)
 *   - 加速度计 3 轴加速度读取 (m/s²)
 *   - 上电自动校准陀螺零偏
 *   - 可配置量程 & DLPF 低通滤波
 *
 * 硬件连接 (WTDKP4C5-S1 J3 排母，已避开摄像头 I2C 总线):
 *   SDA → GPIO54 (J3-2)
 *   SCL → GPIO53 (J3-4)
 *   INT → GPIO40 (J3-34, 可选)
 *   VCC → 3.3V  (J3 任意 3.3V)
 *   GND → GND   (J3-6/8/13)
 *   AD0 → GND   (地址 0x68) / VCC (地址 0x69)
 */

#include <stdbool.h>
#include <stdint.h>

/*============================================================================
 * I2C 引脚 & 总线配置（根据你的接线修改）
 *============================================================================*/
#define MPU6050_I2C_PORT          1       /* I2C_NUM_1 — 独立总线，J3排母: SDA=GPIO54, SCL=GPIO53 */
#define MPU6050_SDA_GPIO          54      /* J3-2, 避开摄像头 I2C (GPIO42/22) */
#define MPU6050_SCL_GPIO          53      /* J3-4, 避开摄像头 I2C (GPIO42/22) */
#define MPU6050_INT_GPIO          40      /* J3-34, 数据就绪中断 (可选, 暂未启用) */
#define MPU6050_I2C_FREQ_HZ       400000  /* 400 kHz 快速模式 */
#define MPU6050_I2C_ADDR          0x68    /* AD0=GND → 0x68, AD0=VCC → 0x69 */

/*============================================================================
 * 陀螺仪量程选择
 *
 *   FS_250   ±250°/s   131.0 LSB/(°/s)   — 慢速机器人
 *   FS_500   ±500°/s    65.5 LSB/(°/s)   — 推荐
 *   FS_1000  ±1000°/s   32.8 LSB/(°/s)   — 中速
 *   FS_2000  ±2000°/s   16.4 LSB/(°/s)   — 快速
 *============================================================================*/
typedef enum {
    MPU6050_GYRO_FS_250  = 0,
    MPU6050_GYRO_FS_500  = 1,
    MPU6050_GYRO_FS_1000 = 2,
    MPU6050_GYRO_FS_2000 = 3,
} mpu6050_gyro_fs_t;

/*============================================================================
 * DLPF 数字低通滤波器带宽
 *
 *   CFG  Accel(Hz)  Gyro(Hz)  延迟(ms)    适用场景
 *    0     260        256      0.98      高速采样
 *    1     184        188      1.9
 *    2      94         98      2.8       100Hz 控制环  ← 推荐
 *    3      44         42      4.8
 *    4      21         20      8.3
 *    5      10         10      13.4
 *    6       5          5      18.6
 *============================================================================*/
typedef enum {
    MPU6050_DLPF_256HZ = 0,
    MPU6050_DLPF_188HZ = 1,
    MPU6050_DLPF_98HZ  = 2,
    MPU6050_DLPF_42HZ  = 3,
    MPU6050_DLPF_20HZ  = 4,
    MPU6050_DLPF_10HZ  = 5,
    MPU6050_DLPF_5HZ   = 6,
} mpu6050_dlpf_t;

/*============================================================================
 * 当前配置（可在调用 mpu6050_init 前修改）
 *============================================================================*/

/** @brief 陀螺仪量程 */
#define MPU6050_GYRO_FS          MPU6050_GYRO_FS_500

/** @brief DLPF 带宽，配合 100Hz 控制环用 98Hz */
#define MPU6050_DLPF_CFG         MPU6050_DLPF_98HZ

/** @brief 采样率分频。采样率 = 1kHz / (1 + divider)，98Hz DLPF 建议不分频 */
#define MPU6050_SMPLRT_DIV       0

/*============================================================================
 * API
 *============================================================================*/

/**
 * @brief 初始化 MPU6050
 *
 * - 初始化 I2C 总线
 * - 唤醒芯片、配置量程和滤波器
 * - 验证 WHO_AM_I 寄存器
 *
 * @return true=初始化成功
 */
bool mpu6050_init(void);

/**
 * @brief 读取陀螺仪数据（已扣除零偏）
 * @param gx/gy/gz  角速度 (rad/s)
 * @return true=读取成功
 */
bool mpu6050_read_gyro(float *gx, float *gy, float *gz);

/**
 * @brief 读取加速度计数据
 * @param ax/ay/az  加速度 (m/s²)
 * @return true=读取成功
 */
bool mpu6050_read_accel(float *ax, float *ay, float *az);

/**
 * @brief 校准陀螺零偏（机器人必须保持静止！）
 * @param num_samples  采样数，推荐 200~500
 * @return true=校准成功
 *
 * 校准结果写入内部静态变量，后续 mpu6050_read_gyro() 自动扣除。
 * 通常在上电初始化时调用一次即可。
 */
bool mpu6050_calibrate(int num_samples);
