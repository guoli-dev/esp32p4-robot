static void fb_set(int x, int y, bool on)
{
    if (x < 0 || x >= 128 || y < 0 || y >= 64) return;
    if (on) s_fb[x + (y / 8) * 128] |=  (1 << (y % 8));
    else    s_fb[x + (y / 8) * 128] &= ~(1 << (y % 8));
}

static void draw_char(int x, int y, char c)
{
    if (c < 0x20 || c > 0x7F) c = '?';
    const uint8_t *g = font[(unsigned char)c - 0x20];
    for (int col = 0; col < 5; col++)
        for (int bit = 0; bit < 8; bit++)
            fb_set(x + col, y + bit, (g[col] >> bit) & 1);
}

static void draw_str(int x, int y, const char *s)
{
    while (*s) { draw_char(x, y, *s); x += 6; s++; }
}

static void draw_hline(int x, int y, int w)
{
    for (int i = 0; i < w; i++) fb_set(x + i, y, true);
}

static void flush(void)
{
    for (int p = 0; p < 8; p++) {
        oled_cmd(0xB0 + p);
        oled_cmd(0x00);
        oled_cmd(0x10);
        oled_data(&s_fb[p * 128], 128);
    }
}

