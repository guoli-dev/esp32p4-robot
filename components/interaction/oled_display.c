#define OLED_WIDTH    128
#define OLED_HEIGHT   64
#define OLED_PAGES    8
#define OLED_ADDR     0x3C

static uint8_t s_fb[128 * 8];  /* 帧缓冲 1024 字节 */
static bool    s_oled_ok = false;  /* 仅在 init 成功后为 true */
static i2c_master_dev_handle_t s_oled_dev = NULL;

/* I2C 写 */
static esp_err_t oled_cmd(uint8_t c)
{
    uint8_t buf[2] = { 0x00, c };
    return i2c_master_transmit(s_oled_dev, buf, 2, pdMS_TO_TICKS(10));
}

static esp_err_t oled_data(const uint8_t *d, size_t n)
{
    uint8_t buf[129];
    buf[0] = 0x40;
    size_t pos = 0;
    while (pos < n) {
        size_t chunk = n - pos;
        if (chunk > 128) chunk = 128;
        memcpy(buf + 1, d + pos, chunk);
        esp_err_t r = i2c_master_transmit(s_oled_dev, buf, chunk + 1, pdMS_TO_TICKS(20));
        if (r) return r;
        pos += chunk;
    }
    return ESP_OK;
}

